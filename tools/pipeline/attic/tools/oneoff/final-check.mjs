// 最终一致性总检：所有存储之间的相互一致。
import { readFileSync, readdirSync, existsSync } from 'node:fs';
const ok = (b) => (b ? 'ok  ' : 'FAIL');
const cat = JSON.parse(readFileSync('knowledge/catalog.json', 'utf8'));
const kbCat = JSON.parse(readFileSync('../dsh-kb-sync/data/kb/catalog.json', 'utf8'));
const recs = readFileSync('knowledge/conversations.jsonl', 'utf8').split('\n').filter(Boolean).length;
const kbRecs = readFileSync('../dsh-kb-sync/data/kb/conversations.jsonl', 'utf8').split('\n').filter(Boolean).length;
const md = readdirSync('../dsh-kb-sync/data/kb/conversations').length;
console.log(ok(cat.length === kbCat.length && cat.length === recs && recs === kbRecs && md === cat.length) + ` 四处计数一致: catalog/jsonl/md = ${cat.length}`);
console.log(ok(cat.every((c, i) => c.idx === i)) + ' catalog idx 连续');
console.log(ok(cat.every((c) => existsSync('../dsh-kb-sync/data/kb/' + c.path))) + ' 所有 path 都存在');
const t = JSON.parse(readFileSync('../dsh-kb-sync/data/kb/topics.json', 'utf8'));
console.log(ok(t.topics.reduce((a, x) => a + x.count, 0) === cat.length) + ` 话题全覆盖（${t.topics.length} 类）`);
const spec = JSON.parse(readFileSync('../dsh-kb-sync/data/kb/specialties.json', 'utf8'));
console.log(ok(true) + ` 专题 ${spec.topics.length} 个，覆盖 ${new Set(spec.topics.flatMap((x) => x.members)).size} 条`);
const f = JSON.parse(readFileSync('../health/facts.json', 'utf8')).facts;
const other = f.filter((x) => x.subject === 'other').length;
console.log(ok(f.every((x) => x.id)) + ` 事实 ${f.length} 条都有稳定 id；归属分离：本人 ${f.length - other} / 朋友 ${other}`);
const k = JSON.parse(readFileSync('../health/knowledge.json', 'utf8'));
const ki = k.sections.reduce((a, s) => a + s.items.length, 0);
console.log(ok(k.sections.every((s) => s.items.every((i) => i.title && i.body))) + ` 结论 ${ki} 条 / ${k.sections.length} 类，必填字段完整`);
const prof = readFileSync('../health/PROFILE.md', 'utf8');
const rows = prof.split('\n').filter((l) => l.startsWith('| '));
const leak = rows.filter((l) => /18\s*岁.*女|月经|阴道|怀孕|罩杯|女朋友/.test(l)).length;
console.log(ok(leak === 0) + ` PROFILE 画像表 ${rows.length} 行，其中朋友的内容 ${leak} 行`);
console.log(ok(existsSync('../health/KNOWLEDGE.md')) + ' KNOWLEDGE.md 存在（助手每次回答前读它）');
console.log(ok(existsSync('../health/FRIEND.md')) + ' FRIEND.md 存在（朋友记录，已与本人档案隔离）');
